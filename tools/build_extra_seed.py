def fetch_json(url, retries=4):
    for attempt in range(retries):
        try:
            return json.load(urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), timeout=60))
        except urllib.error.HTTPError as exc:
            if exc.code == 429 and attempt < retries - 1:
                time.sleep(60)
                continue
            raise


def file_info(name):
    params = {"action": "query", "format": "json", "titles": f"File:{name}", "prop": "imageinfo", "iiprop": "extmetadata"}
    page = next(iter(fetch_json("https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode(params))["query"]["pages"].values()))
    meta = page["imageinfo"][0].get("extmetadata", {})
    artist = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", meta.get("Artist", {}).get("value", ""))).strip()[:70] or "autor nieznany"
    license_name = meta.get("LicenseShortName", {}).get("value", "")
    url = f"https://commons.wikimedia.org/wiki/Special:FilePath/{urllib.parse.quote(name)}?width=1200"
    return url, f"{artist}, {license_name}, Wikimedia Commons", name


def find_image(term):
    params = {
        "action": "query", "format": "json", "generator": "search", "gsrnamespace": 6,
        "gsrsearch": f"{term} filetype:bitmap", "gsrlimit": 10, "prop": "imageinfo",
        "iiprop": "url|extmetadata|size|mime",
    }
    data = fetch_json("https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode(params))
    pages = sorted(data.get("query", {}).get("pages", {}).values(), key=lambda p: p.get("index", 0))
    for page in pages:
        info = page["imageinfo"][0]
        meta = info.get("extmetadata", {})
        name = page["title"][5:]
        license_name = meta.get("LicenseShortName", {}).get("value", "")
        if info.get("mime") not in ("image/jpeg", "image/png") or info.get("width", 0) < 500:
            continue
        if any(word in name.lower() for word in BAD_WORDS):
            continue
        if not any(word in license_name.lower() for word in FREE):
            continue
        artist = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", meta.get("Artist", {}).get("value", ""))).strip()
        artist = artist[:70] or "autor nieznany"
        url = f"https://commons.wikimedia.org/wiki/Special:FilePath/{urllib.parse.quote(name)}?width=1200"
        return url, f"{artist}, {license_name}, Wikimedia Commons", name
    return None


def find_area(query, country, level):
    params = {
        "q": query, "countrycodes": country, "format": "jsonv2", "limit": "5", "polygon_geojson": "1",
        "polygon_threshold": str(THRESHOLD[level]), "accept-language": "pl",
    }
    for r in fetch_json("https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode(params)):
        if r.get("geojson", {}).get("type") in ("Polygon", "MultiPolygon") and (
                r.get("type") in GOOD_TYPES or r.get("category") == "boundary"):
            return r
    return None


def main(only=None):
    questions = {q["title"]: q for q in json.loads(OUT_QUESTIONS.read_text(encoding="utf-8"))} if OUT_QUESTIONS.exists() else {}
    areas = json.loads(OUT_AREAS.read_text(encoding="utf-8"))
    failed = []
    for set_slug, category, title, level, area_name, parts, search, description, facts in ITEMS:
        if only and title not in only:
            continue
        if title in questions and title in areas and not only:
            continue
        try:
            time.sleep(6)
            image = file_info(FILES[title]) if title in FILES else find_image(search)
            if not image:
                failed.append((title, "zdjęcie"))
                print(f"BRAK ZDJĘCIA  {title}")
                continue
            found = []
            for query, country in parts:
                time.sleep(1.2)
                r = find_area(query, country, level)
                if not r:
                    break
                found.append(r)
            if len(found) != len(parts):
                failed.append((title, "granica"))
                print(f"BRAK GRANICY  {title}: {parts}")
                continue
        except Exception as exc:
            failed.append((title, str(exc)))
            print(f"BŁĄD  {title}: {exc}")
            continue
        url, credit, file_name = image
        geoms = [r["geojson"] for r in found]
        areas[title] = {
            "level": level, "name": area_name,
            "geojson": {"type": "GeometryCollection", "geometries": geoms} if len(geoms) > 1 else geoms[0],
        }
        questions[title] = {
            "title": title, "category": category, "location_name": area_name,
            "lat": round(float(found[0]["lat"]), 5), "lng": round(float(found[0]["lon"]), 5),
            "description": description, "image_url": url, "image_credit": credit,
            "facts": [{"label": label, "value": value} for label, value in facts], "sets": [set_slug],
        }
        print(f"ok  {title}  |  {file_name}  |  {found[0]['display_name'][:60]}")
        OUT_QUESTIONS.write_text(json.dumps(list(questions.values()), ensure_ascii=False, indent=1), encoding="utf-8")
        OUT_AREAS.write_text(json.dumps(areas, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"Gotowe: {len(questions)} pytań w {OUT_QUESTIONS.name}. Problemy: {failed or 'brak'}")


if __name__ == "__main__":
    main(set(sys.argv[1:]) or None)
